def poly_from_list(coeffs_low_to_high):
    return fmpz_poly([int(c) for c in coeffs_low_to_high])


def N_of(h, eng):
    """N_h(x) = sum_k h_k A^k B^(m-k), h given low-to-high (ints)."""
    m = len(h) - 1
    N = fmpz_poly([0])
    Apow = [fmpz_poly([1])]
    Bpow = [fmpz_poly([1])]
    for _ in range(m):
        Apow.append(Apow[-1] * eng.A)
        Bpow.append(Bpow[-1] * eng.B)
    for k, hk in enumerate(h):
        if hk:
            N += int(hk) * Apow[k] * Bpow[m - k]
    return N


