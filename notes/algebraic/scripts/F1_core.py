"""F1 forward search: core routines (stage A of PLAN-forward-search.md).

Backend: python-flint 0.9.0 only (FLINT/Arb).  PARI/GP is not installed in this
environment (installing cypari2 was not permitted in the stage-A session), so
polredabs / nfsubfields / polgalois are replaced by the exact routines below.

Objects (F1.md section 2):
  engine g = A/B : P^1 -> P^1 over Q, fibre polynomial F_lam(x) = A(x) - lam*B(x);
  h in Z[T] irreducible of degree m, lam a root;
  N_h(x) = sum_k h_k A(x)^k B(x)^(m-k)  (= A_lam viewed over Q, degree n = d*m).

Routines:
  cycle_table(eng, l)   decomposition type of F_lam mod l for every lam in F_l;
  filter_h(h, eng, ...) necessary condition at primes where h splits completely;
  certify(h, eng)       exact test: does B_h = Q[x]/(N_h) contain a degree-d
                        subfield K with K*Q(lam) = B_h?  Returns K.

Exactness of certify (F1.md section 3.3):
  * orbit sizes of G = Gal(N_h) on ordered pairs of roots come from an exact
    factorisation over Q of Q_c(T) = Res_x(N_h(x), N_h(T - c x)), required
    squarefree;
  * each pair (i, j) is assigned to its factor by Arb ball arithmetic; the
    assignment is accepted only when exactly one factor's root ball overlaps
    the pair's ball, so it is rigorous;
  * a G-invariant equivalence relation with blocks transversal to the fibres is
    searched among unions of orbitals; K is generated by block sums, and its
    minimal polynomial is read off balls that each contain a unique integer.
Nothing in a decision depends on floating point without a rigorous enclosure.
"""

from fractions import Fraction
from itertools import combinations
from math import gcd

from flint import (acb, arb, ctx, fmpq, fmpz, fmpz_mpoly_ctx, fmpz_poly,
                   nmod_poly)

X = fmpz_poly([0, 1])

# ----------------------------------------------------------------------------
# engines
# ----------------------------------------------------------------------------


class Engine:
    """g = A/B with A, B in Z[x] coprime, deg A = d > deg B (pole of order
    d - deg B at infinity).  `branch` lists the finite branch values (Fractions);
    infinity is always a branch value."""

    def __init__(self, name, A, B, branch):
        self.name = name
        self.A = A
        self.B = B
        self.d = A.degree()
        self.branch = [Fraction(b) for b in branch]

    def fibre(self, lam_num, lam_den=1):
        """Integer fibre polynomial lam_den*A - lam_num*B."""
        return lam_den * self.A - lam_num * self.B

    def __repr__(self):
        return self.name


def pp(p, q):
    """g = x^p (1-x)^q, p, q > 0.  Branch values 0, inf, p^p q^q/(p+q)^(p+q)."""
    assert p > 0 and q > 0
    A = X**p * (1 - X)**q
    lam_star = Fraction(p**p * q**q, (p + q)**(p + q))
    if q % 2 == 1:
        pass  # sign already inside (1-x)^q; lam_star is the value at p/(p+q)
    return Engine("pp(%d,%d)" % (p, q), A, fmpz_poly([1]), [0, lam_star])


def tri(D):
    """g = x^D/(1-x).  Fibre x^D + lam x - lam (P1' section 1: tri(D) = pp(D,-1)).
    Branch values 0, inf, g(D/(D-1)) = -D^D/(D-1)^(D-1)."""
    A = X**D
    B = 1 - X
    lam_star = Fraction(-D**D, (D - 1)**(D - 1))
    return Engine("tri(%d)" % D, A, B, [0, lam_star])


