class CertResult:
    def __init__(self, status, **kw):
        self.status = status  # 'solution' | 'none' | 'reducible' | 'degenerate'
        self.__dict__.update(kw)

    def __repr__(self):
        keys = [k for k in self.__dict__ if k != "status"]
        return "CertResult(%s, %s)" % (self.status, ", ".join("%s=%s" % (k, self.__dict__[k]) for k in keys))


def _orbitals(N, max_c=40, prec_bits=(128, 256, 512, 1024, 2048, 4096)):
    """Exact G-orbitals on ordered pairs of roots of N (G = Galois group).

    Returns (roots, O, factors) where O[i][j] is the orbital index of (i, j).
    Raises RuntimeError if no admissible c or precision is found."""
    n = N.degree()
    for c in range(2, max_c):
        Q = pair_resultant(N, c)
        if Q.degree() != n * n or not is_squarefree(Q):
            continue
        _, facs = Q.factor()
        facs = [f for f, e in facs]
        old = ctx.prec
        try:
            for pb in prec_bits:
                ctx.prec = pb
                rts = roots_balls(N)
                if not _balls_disjoint(rts):
                    continue
                froots = [roots_balls(f) for f in facs]
                O = [[None] * n for _ in range(n)]
                ok = True
                for i in range(n):
                    ci = c * rts[i]
                    for j in range(n):
                        v = rts[j] + ci
                        hits = [k for k, fr in enumerate(froots) if any(v.overlaps(z) for z in fr)]
                        if len(hits) != 1:
                            ok = False
                            break
                        O[i][j] = hits[0]
                    if not ok:
                        break
                if ok:
                    return rts, O, facs, c, pb
        finally:
            ctx.prec = old
    raise RuntimeError("no admissible c / precision for orbitals")


def _fibres(rts, eng, h):
    """Fibre index of each root: lam_i = A(r_i)/B(r_i), matched to the roots of
    h by rigorous ball overlap."""
    hr = roots_balls(fmpz_poly([int(c) for c in h]))
    assert _balls_disjoint(hr)
    fib = []
    for z in rts:
        lam = _eval_poly_acb(eng.A, z) / _eval_poly_acb(eng.B, z)
        hits = [k for k, w in enumerate(hr) if lam.overlaps(w)]
        if len(hits) != 1:
            return None
        fib.append(hits[0])
    return fib


def _block_systems(O, fib, m):
    """All G-invariant equivalence relations, given as unions S of orbitals
    (plus the diagonal), whose classes have size m and meet every fibre once."""
    n = len(O)
    diag = O[0][0]
    # orbitals through root 0 that leave fibre(0)
    cross = sorted({O[0][j] for j in range(n) if fib[j] != fib[0]})
    size_at0 = {k: [j for j in range(n) if O[0][j] == k] for k in cross}
    cand = [k for k in cross if len(size_at0[k]) <= m - 1]
    out = []
    for r in range(1, len(cand) + 1):
        for S in combinations(cand, r):
            members = [0] + [j for k in S for j in size_at0[k]]
            if len(members) != m:
                continue
            if len({fib[j] for j in members}) != m:
                continue
            Sset = set(S) | {diag}
            # equivalence relation check: classes from root i
            classes = {}
            ok = True
            for i in range(n):
                cl = frozenset(j for j in range(n) if O[i][j] in Sset)
                if len(cl) != m or len({fib[j] for j in cl}) != m:
                    ok = False
                    break
                classes[i] = cl
            if not ok:
                continue
            for i in range(n):
                for j in classes[i]:
                    if classes[j] != classes[i]:
                        ok = False
                        break
                if not ok:
                    break
            if ok:
                out.append(sorted(set(classes.values()), key=lambda b: min(b)))
    return out


def certify(h, eng, want_all=False):
    """Exact test of F1.md Proposition 2.1 for lam a root of h (degree m >= 1).

    Returns CertResult with status
      'solution'   : K (fmpz_poly, monic, irreducible, degree d) with
                     K (x) Q(lam) = A_lam;  `blocks`, `c` record the witness;
      'none'       : N_h irreducible and no such K exists  [exact];
      'reducible'  : N_h reducible over Q (A_lam is not a field; recorded,
                     not decided here);
      'degenerate' : lam is a branch value or h is not irreducible/squarefree.
    """
    m = len(h) - 1
    hp = fmpz_poly([int(c) for c in h])
    if m < 1 or not is_squarefree(hp) or len(hp.factor()[1]) != 1 or hp.factor()[1][0][1] != 1:
        return CertResult("degenerate", reason="h not irreducible")
    for b in eng.branch:
        if hp(fmpq(b.numerator, b.denominator)) == 0:
            return CertResult("degenerate", reason="branch value")
    N = N_of(h, eng)
    n = N.degree()
    if n != eng.d * m:
        return CertResult("degenerate", reason="degree drop (lam at infinity?)")
    _, facs = N.factor()
    if len(facs) != 1 or facs[0][1] != 1:
        return CertResult("reducible", degrees=sorted(f.degree() for f, e in facs for _ in range(e)))
    if m == 1:
        return CertResult("solution", K=_monic_integral(N), blocks=None, c=None, trivial=True)
    rts, O, Qfacs, c, pb = _orbitals(N)
    old = ctx.prec
    ctx.prec = pb
    try:
        fib = _fibres(rts, eng, h)
    finally:
        ctx.prec = old
    if fib is None:
        raise RuntimeError("fibre assignment failed")
    systems = _block_systems(O, fib, m)
    orbital_sizes = sorted(f.degree() for f in Qfacs)
    if not systems:
        return CertResult("none", orbital_sizes=orbital_sizes)
    lc = int(N.leading_coefficient())
    results = []
    for blocks in systems:
        K = _field_from_blocks(N, rts, blocks, lc)
        if K is None:
            raise RuntimeError("could not isolate K's minimal polynomial")
        results.append(K)
        if not want_all:
            break
    return CertResult("solution", K=results[0], Ks=results, blocks=systems[0],
                      orbital_sizes=orbital_sizes, c=c, trivial=False)


def _monic_integral(N):
    """Monic integral polynomial for lc*x where x is a root of N."""
    co = [int(c) for c in N.coeffs()]
    n = len(co) - 1
    lc = co[-1]
    return fmpz_poly([co[i] * lc**(n - 1 - i) for i in range(n)] + [1])


def _refine_roots(N, old_balls):
    """Roots of N at the current precision, indexed like old_balls (each new
    ball must overlap exactly one old ball)."""
    new = roots_balls(N)
    out = [None] * len(old_balls)
    for z in new:
        hits = [i for i, w in enumerate(old_balls) if z.overlaps(w)]
        if len(hits) != 1 or out[hits[0]] is not None:
            return None
        out[hits[0]] = z
    return out


def _field_from_blocks(N, rts, blocks, lc):
    """Minimal polynomial of a primitive element of K from block power sums
    sum_{i in B} (lc*r_i)^k, k = 1, 2, ...  (algebraic integers in K, since
    lc*r_i is integral).  Each is fixed by the block stabiliser, so its
    conjugates are the block sums and prod (t - theta_B) has integer
    coefficients; balls isolate them rigorously."""
    d = len(blocks)
    old = ctx.prec
    try:
        cur = rts
        for pb in (256, 512, 1024, 2048, 4096, 8192):
            ctx.prec = pb
            ref = _refine_roots(N, cur)
            if ref is None:
                continue
            cur = ref
            for k in range(1, 6):
                th = []
                for B in blocks:
                    s = acb(0)
                    for i in B:
                        s += (lc * cur[i]) ** k
                    th.append(s)
                if not _balls_disjoint(th):
                    continue
                f = poly_from_roots_int(th)
                if f is None:
                    break  # more precision
                if f.degree() == d and len(f.factor()[1]) == 1 and is_squarefree(f):
                    return f
    finally:
        ctx.prec = old
    return None


