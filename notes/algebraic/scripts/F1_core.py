def has_root_in(f, base):
    """Exact: does f (irreducible over Q) have a root in Q[y]/(base)?
    Trager: with Nm(T) = Res_y(base(y), f(T - c y)) squarefree, factors of f
    over Q(y) of degree k correspond to factors of Nm of degree k*deg(base)."""
    nb = base.degree()
    for c in range(0, 60):
        Nm = norm_resultant(f, base, c)
        if Nm.degree() != f.degree() * nb or not is_squarefree(Nm):
            continue
        _, facs = Nm.factor()
        return any(g.degree() == nb for g, _ in facs)
    raise RuntimeError("no squarefree Trager norm")


def fields_isomorphic(f1, f2):
    """Exact isomorphism test of Q[t]/f1 and Q[t]/f2 (both irreducible)."""
    if f1.degree() != f2.degree():
        return False
    return has_root_in(f1, f2)


def _is_prime(k):
    return k > 1 and all(k % q for q in range(2, int(k**0.5) + 1))


def galois_certificate(f, primes=None):
    """Proved Galois group label for irreducible f of degree d, via Dedekind
    factorisation patterns (each pattern is the cycle type of a Frobenius,
    hence of an element of G):
      transitive (irreducible) +
      primitive  (d prime, or a (d-1)-cycle => 2-transitive) +
      a transposition                   => 'S_d'   [Proof]
      a p-cycle, p prime <= d-3, or a 3-cycle => contains A_d (Jordan) => 'A_d'
                    or 'S_d' by the discriminant  [Proof]
    Otherwise returns ('?', patterns) with the observed pattern set
    [Computed, cycle statistics only]."""
    d = f.degree()
    if primes is None:
        primes = [p for p in range(3, 3000) if _is_prime(p)]
    disc = f.discriminant()
    lc = int(f.leading_coefficient())
    pats = set()
    for p in primes:
        if disc % p == 0 or lc % p == 0:
            continue
        fl = nmod_poly([int(c) % p for c in f.coeffs()], p)
        _, fac = fl.factor()
        pats.add(tuple(sorted(g.degree() for g, _ in fac)))
    primitive = _is_prime(d) or (1, d - 1) in pats
    has_transp = any(sorted(p) == [1] * (d - 2) + [2] for p in pats)
    contains_A = False
    for p in pats:
        # an element whose cycle type has exactly one cycle of prime length r,
        # all other cycle lengths coprime to r: a power is a pure r-cycle
        for r in set(p):
            if not (_is_prime(r) and (r == 3 or r <= d - 3)):
                continue
            if list(p).count(r) == 1 and all(gcd(s, r) == 1 for s in p if s != r):
                contains_A = True
    if primitive and has_transp:
        return ("S%d" % d, "proved")
    if primitive and contains_A:
        return (("A%d" % d) if _is_square(int(disc)) else ("S%d" % d), "proved")
    return ("?", sorted(pats))


def _is_square(k):
    if k < 0:
        return False
    from math import isqrt
    r = isqrt(k)
    return r * r == k


def signature(f):
    """(r1, r2) of Q[t]/f for squarefree f, rigorous: a root ball whose
    imaginary part excludes 0 holds a nonreal root; a ball meeting the real
    axis whose conjugate overlaps no other ball holds a real root (its
    conjugate root lies in the conjugate ball, hence in the same ball)."""
    old = ctx.prec
    try:
        for pb in (64, 128, 256, 512, 1024):
            ctx.prec = pb
            rts = roots_balls(f)
            r1, ok = 0, True
            for i, z in enumerate(rts):
                if not z.imag.contains(0):
                    continue
                zc = z.conjugate()
                if any(zc.overlaps(w) for j, w in enumerate(rts) if j != i):
                    ok = False
                    break
                r1 += 1
            if ok:
                return (r1, (f.degree() - r1) // 2)
    finally:
        ctx.prec = old
    raise RuntimeError("signature: precision exhausted")
