_C2 = fmpz_mpoly_ctx.get(("x", "T"), "lex")
_x2, _T2 = _C2.gens()


def _to_mpoly_x(f):
    out = _C2.from_dict({(i, 0): int(c) for i, c in enumerate(f.coeffs()) if c})
    return out


def _mpoly_T_to_univ(P):
    d = P.to_dict()
    if not d:
        return fmpz_poly([0])
    deg = max(k[1] for k in d)
    co = [0] * (deg + 1)
    for k, v in d.items():
        assert k[0] == 0
        co[k[1]] = int(v)
    return fmpz_poly(co)


def pair_resultant(N, c):
    """Q_c(T) = Res_x(N(x), N(T - c x)); its roots are r_j + c r_i over all
    ordered pairs (i, j) of roots of N (up to a nonzero constant)."""
    Nx = _to_mpoly_x(N)
    NT = Nx.compose(_T2 - c * _x2, _T2)
    return _mpoly_T_to_univ(Nx.resultant(NT, "x"))


def norm_resultant(f_over, f_base, c):
    """Res_y(f_base(y), f_over(T - c y)) for Trager's algorithm: the norm from
    Q[y]/f_base of f_over(T - c y)."""
    fb = _to_mpoly_x(f_base)
    fo = _to_mpoly_x(f_over).compose(_T2 - c * _x2, _T2)
    return _mpoly_T_to_univ(fb.resultant(fo, "x"))


def is_squarefree(f):
    return f.gcd(f.derivative()).degree() == 0


