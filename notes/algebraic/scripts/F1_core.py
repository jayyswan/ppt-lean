def _branch_residues(eng, l):
    out = set()
    for b in eng.branch:
        if b.denominator % l == 0:
            continue  # reduces to infinity, which is never a finite residue
        out.add((b.numerator * pow(b.denominator, -1, l)) % l)
    return out


def cycle_table(eng, l):
    """For each residue lam in F_l: the sorted tuple of factor degrees of
    A - lam*B mod l, or None if lam is a branch residue or the fibre is not
    squarefree of degree d mod l (inconclusive residue)."""
    Al = nmod_poly([int(c) % l for c in eng.A.coeffs()], l)
    Bl = nmod_poly([int(c) % l for c in eng.B.coeffs()], l)
    bad = _branch_residues(eng, l)
    table = []
    for lam in range(l):
        if lam in bad:
            table.append(None)
            continue
        F = Al - lam * Bl
        if F.degree() != eng.d:
            table.append(None)
            continue
        if F.gcd(F.derivative()).degree() > 0:
            table.append(None)
            continue
        _, facs = F.factor()
        table.append(tuple(sorted(f.degree() * e for f, e in facs)))
    return table


def primes_between(a, b):
    sieve = bytearray([1]) * b
    sieve[0] = sieve[1] = 0
    for i in range(2, int(b**0.5) + 1):
        if sieve[i]:
            sieve[i * i::i] = bytearray(len(sieve[i * i::i]))
    return [p for p in range(a, b) if sieve[p]]


DEFAULT_PRIMES = primes_between(11, 1200)
LONG_PRIMES = primes_between(11, 200000)


class TableCache:
    """Cycle-type entries computed lazily, one residue at a time (so long
    prime lists cost only what the filter actually looks up)."""

    def __init__(self, eng):
        self.eng = eng
        self._t = {}
        self._ctx = {}

    def entry(self, l, lam):
        key = (l, lam)
        if key in self._t:
            return self._t[key]
        if l not in self._ctx:
            Al = nmod_poly([int(c) % l for c in self.eng.A.coeffs()], l)
            Bl = nmod_poly([int(c) % l for c in self.eng.B.coeffs()], l)
            self._ctx[l] = (Al, Bl, _branch_residues(self.eng, l))
        Al, Bl, bad = self._ctx[l]
        val = None
        if lam not in bad:
            F = Al - lam * Bl
            if F.degree() == self.eng.d and F.gcd(F.derivative()).degree() == 0:
                val = tuple(sorted(g.degree() * e for g, e in F.factor()[1]))
        self._t[key] = val
        return val

    def get(self, l):
        return [self.entry(l, lam) for lam in range(l)]


def filter_h(h, eng, primes=None, need=12, cache=None):
    """Necessary condition for (eng, lam) to be a solution, lam a root of h.

    At each prime l with l not dividing lc(h) and h squarefree and split
    completely mod l, the cycle types of the fibres at all roots of h mod l must
    agree (F1.md Lemma 3.2).  Returns (verdict, info):
      ('reject', l)   a prime l where two roots disagree  [Proof: not a solution]
      ('pass', k)     k >= need usable primes, no disagreement
      ('few', k)      fewer than `need` usable primes in the list (inconclusive)
    """
    if primes is None:
        primes = DEFAULT_PRIMES
    if cache is None:
        cache = TableCache(eng)
    m = len(h) - 1
    used = 0
    for l in primes:
        if h[-1] % l == 0:
            continue
        hl = nmod_poly([int(c) % l for c in h], l)
        if hl.gcd(hl.derivative()).degree() > 0:
            continue
        rts = hl.roots()
        if len(rts) != m:
            continue
        types = [cache.entry(l, int(r)) for r, _ in rts]
        if any(t is None for t in types):
            continue
        used += 1
        if any(t != types[0] for t in types[1:]):
            return ("reject", l)
        if used >= need:
            return ("pass", used)
    return ("few", used)


