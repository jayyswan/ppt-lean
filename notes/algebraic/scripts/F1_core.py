def roots_balls(f):
    """Rigorous root balls of a squarefree fmpz_poly (each multiplicity 1)."""
    r = f.complex_roots()
    assert all(e == 1 for _, e in r), "not squarefree"
    return [z for z, _ in r]


def _balls_disjoint(bs):
    for i in range(len(bs)):
        for j in range(i + 1, len(bs)):
            if bs[i].overlaps(bs[j]):
                return False
    return True


def _eval_poly_acb(f, z):
    acc = acb(0)
    for c in reversed(f.coeffs()):
        acc = acc * z + acb(int(c))
    return acc


def _unique_int(a):
    """a is an acb ball; return the unique integer it contains, else None."""
    re, im = a.real, a.imag
    if not im.contains(0):
        return None
    k = re.unique_fmpz()  # the unique integer in the ball, or None
    return None if k is None else int(k)


def poly_from_roots_int(balls):
    """Monic integer polynomial prod (t - z) from balls known (by Galois
    invariance) to give integer coefficients.  Returns None if some
    coefficient ball does not isolate a unique integer."""
    co = [acb(1)]
    for z in balls:
        new = [acb(0)] * (len(co) + 1)
        for i, c in enumerate(co):
            new[i + 1] += c
            new[i] -= c * z
        co = new
    out = []
    for c in co:
        k = _unique_int(c)
        if k is None:
            return None
        out.append(k)
    return fmpz_poly(out)


